-- PhishDetect Database Schema
-- Run this script in your Supabase SQL editor to create the required table

CREATE TABLE IF NOT EXISTS url_analysis_cache (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  url TEXT NOT NULL UNIQUE,
  final_verdict TEXT NOT NULL, -- e.g., 'Safe', 'Suspicious', 'Malicious'
  full_report JSONB NOT NULL,
  last_scanned_at TIMESTAMPTZ WITH TIME ZONE NOT NULL
);

-- Create an index on the URL for fast lookups
CREATE INDEX IF NOT EXISTS idx_url ON url_analysis_cache(url);

-- Add a comment to the table
COMMENT ON TABLE url_analysis_cache IS 'Cache table for URL analysis results from external security services';

